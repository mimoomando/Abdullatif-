from __future__ import annotations

import os
from typing import Optional, Tuple

# ⚠️ الترتيب مقصود: العاري أوّلًا، ثم ما يلحقه ويندوز.
NAMES: Tuple[str, ...] = ("STOP", "STOP.txt", "stop", "stop.txt")


def path(root: str = ".") -> Optional[str]:
    """مسارُ ملفّ الإيقاف إن وُجد — أو `None`."""
    for name in NAMES:
        p = os.path.join(root, name)
        if os.path.exists(p):
            return p
    return None


def active(root: str = ".") -> bool:
    return path(root) is not None


def reason(root: str = ".") -> str:
    """
    ما كتبه المستخدم داخل الملفّ — يُعرض في السجلّ.

    ⭐ فمن أوقف البوت الخميس وعاد الاثنين لا يذكر لماذا. وسطرٌ داخل
    الملفّ يذكّره.
    """
    p = path(root)
    if p is None:
        return ""
    try:
        with open(p, encoding="utf-8", errors="replace") as fh:
            return fh.read(200).strip()
    except OSError:
        return ""


def watching(root: str = ".") -> str:
    """
    سطرٌ واحدٌ يقول **أين** يُنتظَر ملفُّ الإيقاف — ⭐ وهو علاجُ KS3.

    ╔══════════════════════════════════════════════════════════════╗
    ║  ⛔⛔ **والعطبُ الذي يسدّه مكتوبٌ في الترويسة ولا كودَ له:**    ║
    ║  [وملفُّ إيقافٍ في المكان الخطأ **لا يوقف شيئًا، ولا يقول**    ║
    ║  **إنّه لم يوقف**].                                           ║
    ║                                                              ║
    ║  ⇒ فمن أنشأ `STOP` على سطح المكتب يرى البوتَ يُعلن             ║
    ║  **فيظنّه معطوبًا، أو — وهو الأسوأ — يظنّه متوقّفًا وهو يعمل.**  ║
    ║  ⭐⭐⭐ **وهو قاعدةُ المشروع بعينها**: [اجعلها تكتب سطرًا حين   ║
    ║  لا تعمل]، **والصمتُ ليس نجاحًا.**                            ║
    ╚══════════════════════════════════════════════════════════════╝

    ⚠️ **ولا يُكشَف المكانُ الخطأ بالتخمين**: [سطحُ المكتب] يختلف
    بالنظام واللغة وبـOneDrive ⇒ **فاشتقاقُه اختراعُ مسار**
    (القاعدة ①). ⇒ **والجوابُ أن يُقال المكانُ الصحيحُ صريحًا**،
    فيقابله المستخدمُ بما فعل.

    ⛔⛔ **وهو للشاشة وحدَها** — `errors.jsonl` **لا يُكتب فيه مسار**
    (القاعدة ③ · وعرفُ LC1 بنصّه).
    """
    return (f"[STOP] kill switch is OFF - put a file named "
            f"{' or '.join(NAMES[:2])} in: {os.path.abspath(root)}")


def banner(root: str = ".") -> str:
    """
    سطرُ الحالة — **لاتينيٌّ أوّلًا**، فنافذة cmd تقلب العربيّة.

    (رآها المستخدم مقلوبةً أوّلَ تشغيل — انظر `Heartbeat`.)

    ⛔ **وكان يقول [no setups announced] وحدَها** — فيقرؤها صاحبُها
    [والتسجيلُ مستمرّ]، **وليس كذلك**: التمريرةُ كلُّها تتوقّف. صُحّح
    2026-09-30 — انظر KS2 في ترويسة الوحدة.
    """
    p = path(root) or ""
    why = reason(root)
    out = [f"[STOP] KILL SWITCH IS ON - not reading, not recording, "
           f"nothing announced. File: {p}"]
    if why:
        out.append(f"       note: {why}")
    out.append("       delete the file to resume.")
    out.append(f"⛔ مفتاح الإيقاف مفعَّل — **لا قراءةَ ولا تسجيل**. "
               f"احذف {p} ليعود.")
    return "\n".join(out)


