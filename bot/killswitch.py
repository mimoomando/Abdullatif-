"""
مفتاح الإيقاف — **ملفٌّ واحد يوقف البوت، وحذفُه يعيده.**

╔══════════════════════════════════════════════════════════════════╗
║  ضع ملفًّا اسمه  STOP  في مجلّد المشروع  ⇒  يتوقّف                 ║
║  احذفه                                    ⇒  يعود من تلقائه      ║
╚══════════════════════════════════════════════════════════════════╝

**ولماذا ملفٌّ لا أمرٌ ولا زرّ؟** لأنّ يومًا يسوء — خبرٌ مفاجئ، أو
سبريدٌ جنونيّ، أو شكٌّ في الإعدادات — تحتاج فيه إيقافًا **في ثانية**،
لا بحثًا عن نافذة cmd بين عشرين نافذة، ولا تذكّرًا لأمر. وإنشاءُ
ملفٍّ فارغٍ يفعله أيُّ أحدٍ تحت الضغط.

⚠️ **وفي مجلّد المشروع وحده — لا على سطح المكتب.** فـ`path()` تفحص
`root` ولا تنزل إلى غيره. ⇒ **وملفُّ إيقافٍ في المكان الخطأ لا يوقف
شيئًا، ولا يقول إنّه لم يوقف** — وهو عينُ خطرِ `STOP.txt` أدناه.
(⛔ **وكان مكتوبًا هنا [على سطح المكتب]** — صُحّح 2026-09-30.)

⭐⭐ **ويقبل `STOP.txt` كما يقبل `STOP`** — وهذا ليس تسامحًا زائدًا:
ويندوز يخفي الامتدادات افتراضًا، والمفكّرةُ تُلحق `.txt` صامتةً. فمن
أنشأ STOP بالمفكّرة يظنّه `STOP` وهو `STOP.txt`. ومفتاحُ إيقافٍ
يفشل صامتًا لأنّ النظام أضاف ثلاثة أحرف **أسوأ من عدمه**.

╔══════════════════════════════════════════════════════════════════╗
║  ⛔⛔⛔ **KS2 — [يوقف التنبيه لا التسجيل] كانت دعوًى في أربعةِ    ║
║  مواضع، والكودُ يوقف الاثنين. كُشف 2026-09-30.**                 ║
╚══════════════════════════════════════════════════════════════════╝

كان هنا: [فالبوت يبقى يقرأ ويحكم ويكتب، ولا يُعلن إعدادًا… فنعرف ما
**كان** سيحدث في الساعات التي أوقفتَه فيها — وهو أنفعُ ما يُقاس].

**و`runner._main_locked` تعمل `continue` قبل `run_once` أصلًا** ⇒
فلا تُقرأ شمعةٌ، ولا يُحكَم حكم، ولا يُكتب سطر. والدعوى في أربعة:

    ① ترويسةُ هذه الوحدة   ② `RUN.md`
    ③ بانرُ `banner()`     ④ اسمُ اختبارٍ يحمل الوعد ولا يفحص منه شيئًا
       [no setups announced]

⛔ **وأخطرُ ما فيه ليس كذبَ الدعوى**: الفجوةُ في `decisions.jsonl`
تصير **غيرَ مميَّزةٍ عن انقطاع الجسر** — وهو بعينه ما أربكنا يوم
09-29 (فجوةُ 12:30 ← 00:10). فللفجوة ثلاثةُ تفاسير: [سوقٌ هادئ] ·
[جسرٌ ساقط] · **[أوقفتَه أنت]** — والثالثُ **لم يكن مكتوبًا في أيّ
ملفّ**. وهو صنفُ RW2: عطبُ بياناتٍ يُقرأ حكمَ سوق.

⇒ **وما صُحّح الآن — بلا تغييرِ سلوكٍ واحد:**
  · الترويسةُ و`RUN.md` والبانرُ يقولون ما يحدث فعلًا
  · **والتوقّفُ يكتب سطرًا في `errors.jsonl`** — عند البدء، وكلَّ
    نصف ساعة، وعند الرفع ⇒ فالفجوةُ لها سببٌ مكتوب

⇒ **وما لم يُقلب، وهو السؤال:** أينبغي أن يبقى التسجيلُ يعمل
ويُكتَم التنبيهُ وحدَه؟

| | الطريق | ثمنُه |
|---|---|---|
| ① | يبقى كما هو — `STOP` يوقف الاثنين | تُفقد ساعاتُ [ما كان سيحدث] |
| ② | يُسجَّل ويُكتَم التنبيه | صفوفُ التوقّف تدخل **كلَّ قياس** بلا تمييز ⇒ فتلزمها رايةٌ في الصفّ، **وقرارٌ: أتُحسَب أم تُستثنى؟** |

⚠️⚠️ **والثاني تغييرُ مادّةِ القياس لا تغييرُ طباعة** — و`decisions.jsonl`
هو مادّةُ كلّ رقمٍ في المشروع. **فالقرارُ منهجيٌّ لا تقنيّ** (كـIN1)،
ولا يُتَّخذ بلا المستخدم.

ومن أراد إيقافًا تامًّا فـ`Ctrl+C` موجود.
"""

from __future__ import annotations

import os
from typing import Optional, Tuple

# ⚠️ الترتيب مقصود: العاري أوّلًا، ثم ما يلحقه ويندوز.
NAMES: Tuple[str, ...] = ("STOP", "STOP.txt", "stop", "stop.txt")


def path(root: str = ".") -> Optional[str]:
    """مسارُ ملفّ الإيقاف إن وُجد — أو `None`."""
    for name in NAMES:
        p = os.path.join(root, name)
        if os.path.exists(p):
            return p
    return None


def active(root: str = ".") -> bool:
    return path(root) is not None


def reason(root: str = ".") -> str:
    """
    ما كتبه المستخدم داخل الملفّ — يُعرض في السجلّ.

    ⭐ فمن أوقف البوت الخميس وعاد الاثنين لا يذكر لماذا. وسطرٌ داخل
    الملفّ يذكّره.
    """
    p = path(root)
    if p is None:
        return ""
    try:
        with open(p, encoding="utf-8", errors="replace") as fh:
            return fh.read(200).strip()
    except OSError:
        return ""


def banner(root: str = ".") -> str:
    """
    سطرُ الحالة — **لاتينيٌّ أوّلًا**، فنافذة cmd تقلب العربيّة.

    (رآها المستخدم مقلوبةً أوّلَ تشغيل — انظر `Heartbeat`.)

    ⛔ **وكان يقول [no setups announced] وحدَها** — فيقرؤها صاحبُها
    [والتسجيلُ مستمرّ]، **وليس كذلك**: التمريرةُ كلُّها تتوقّف. صُحّح
    2026-09-30 — انظر KS2 في ترويسة الوحدة.
    """
    p = path(root) or ""
    why = reason(root)
    out = [f"[STOP] KILL SWITCH IS ON - not reading, not recording, "
           f"nothing announced. File: {p}"]
    if why:
        out.append(f"       note: {why}")
    out.append("       delete the file to resume.")
    out.append(f"⛔ مفتاح الإيقاف مفعَّل — **لا قراءةَ ولا تسجيل**. "
               f"احذف {p} ليعود.")
    return "\n".join(out)


CLEARED = ("[OK] KILL SWITCH REMOVED - back to normal.\n"
           "✅ رُفع مفتاح الإيقاف — عاد البوت.")
