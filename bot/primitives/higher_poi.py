"""
سندُ الإطار الأكبر — **الأوردر بلوك الصغير لا يقوم وحده.**

╔══════════════════════════════════════════════════════════════════╗
║  «الأوردر بلوك نقدر ناخذه على **كلّ الفريمات**، ولكن بدّه يكون    ║
║   في أيّ احترافيّة بالموضوع **بدّك تكون مرتكز على نقاط اهتمام     ║
║   أكبر**»                                                        ║
║                                                                  ║
║  «إذا بدّك تاخذ أوردر بلوك على فريم **الدقيقة**… بدّه يكون عندك   ║
║   **تأكيد من مناطق عليا** — يعني من **نقطة اهتمام أكبر**»        ║
║                                                                  ║
║  «شفت كيف تتاخذ الأوردر بلوك على الدقيقة؟ **بدّه يكون عندك       ║
║   نقطة اهتمام من نطاق أعلى**»                                    ║
╚══════════════════════════════════════════════════════════════════╝

**وقالها بتدرّج** (الأوردر بلوك · ج1):

    «الأوردر بلوك اللي بيكون على **أربع ساعات** — هيدا **ما بحاجة**
     لأني أعمل له نقاط اهتمام. أما اللي بيكون على **الربع ساعة** —
     **بحاجة لنقاط اهتمام من إطار أكبر** ليكون ناجحًا وفعّالًا…
     **وكلّ ما قلّ الفريم، كلّ ما بدّه إطارات مرتبطة فيه**»

⭐ **وهو مرشِّحٌ لا مولِّد** — أسلمُ ما يُبنى: لا يخترع إعدادًا، يردّ
إعدادًا لا سندَ له. 🔴 وأثرُه كبير: **170 من 229** قرارًا في أسبوع
09-14 كانت على M15.

🔶 **وما لم ينطق به:**

| | |
|---|---|
| **H1** | لم يُذكر. والتدرّج يقول إنّه بين الطرفين، فلا رقمَ له ⇒ لا يُشترط |
| **أيُّ إطارٍ أعلى** لـM15؟ | قال «نطاق أعلى» ولم يسمِّه — والمختار H1، وهو **اختيار** |
| **ما معنى «مرتكز»؟** | تداخلُ المنطقتين سعرًا — وهو أقربُ ما يُقرأ، ويبقى تأويلًا |

⇒ فالشرطُ `SOURCE` والتفاصيلُ الثلاثة تأويل. **يُقاس قبل أن يُثبَّت.**
"""

from __future__ import annotations

from typing import Optional, Sequence

from .liquidity_map import Internal

# الأطر التي نصَّ على احتياجها سندًا — ولا يُزاد عليها بالقياس وحده
NEEDS_SUPPORT = ("M15", "M5", "M3", "M1")

# والذي نصَّ على استغنائه
NEEDS_NOTHING = ("H4", "D1", "W1")


def overlaps(a: Internal, b: Internal, tolerance: float = 0.0) -> bool:
    """هل تتداخل المنطقتان سعرًا؟ (لا زمنًا — فالإطاران مختلفان)"""
    return (a.bottom - tolerance) <= b.top and (b.bottom - tolerance) <= a.top


def support(
    zone: Internal,
    higher: Sequence[Internal],
    tolerance: float = 0.0,
) -> Optional[Internal]:
    """
    أقربُ منطقةٍ من الإطار الأكبر تسند هذه — أو `None`.

    و«الأقرب» بالمنتصف: منطقتان تسندان، فالتي مركزُها أدنى إلى مركز
    الصغيرة أدلُّ على «الارتكاز».
    """
    found = [h for h in higher if overlaps(zone, h, tolerance)]
    if not found:
        return None
    return min(found, key=lambda h: abs(h.midpoint - zone.midpoint))


def required_for(timeframe: str) -> bool:
    """
    هل يحتاج هذا الإطار سندًا من أعلى؟

    ⛔ والقائمتان **منصوصتان**، وما بينهما (H1) لا يُشترط — فالتدرّج
    «كلّ ما قلّ الفريم» يرتّب ولا يعطي عتبة، ولا تُخترَع عتبةٌ من ترتيب.
    """
    return timeframe.upper() in NEEDS_SUPPORT
