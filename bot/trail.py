"""
إدارةُ الصفقة بعد فتحها — **نقلُ الوقف مع الأهداف.**

╔══════════════════════════════════════════════════════════════════╗
║  بلغ الهدف ١  ⇒  الوقف إلى **الدخول + دولار**                     ║
║  بلغ الهدف ٢  ⇒  الوقف إلى **الهدف ١**                            ║
║  بلغ الهدف ٣  ⇒  الوقف إلى **الهدف ٢**    … وهكذا                 ║
╚══════════════════════════════════════════════════════════════════╝

⭐⭐ **الخطوة الأولى منصوصة** (الأوردر بلوك · ج3):

    «بس ضرب الهدف الأوّل، **بدك تأمّن**… بترفع الستوب لوز **لفوق
     دخولك بدولار**، مشان إذا صار انعكاس قوي انت **بتطلع صفر**»

⚠️ **والدولارُ ليس نقطةَ تعادل — هو فوقها.** وعلّتُه في قوله نفسِه:
«بتطلع **صفر**». فالتعادل الحرفيّ يخرجك بخسارة السبريد، والدولار
يغطّيها فتخرج صفرًا فعلًا. ولذلك لا يُختصر إلى «الدخول».

⭐ **وما بعد الخطوة الأولى — كان `USER`، وصار `SOURCE`** (2026-09-26):

قال المستخدم في 2026-09-20:

    «عند وصول أوّل تي بي ينقل الوقف إلى الدخول، وعند الوصول إلى ثاني
     تي بي ينقل الوقف إلى أوّل تي بي — وهكذا»

ثم قال «**ابنها مثل ما قال المدرّب**». وكُتب هنا يومَها: «🔶 والمدرّب
لم ينطق إلّا بالأولى — فما بعدها `USER` باسمه، لا يُنسب إليه».

╔══════════════════════════════════════════════════════════════════╗
║  ⛔ **وذلك لم يعد صحيحًا.** فدرسُ «تحديد نقاط الأهداف ونقاط وقف    ║
║  الخسارة» (وصل خامًّا 2026-09-26) ينطق بالسلّم كلِّه في جملة:      ║
║                                                                  ║
║    «بس ضربنا التي بي الأوّل بنيجي **بحرّك الستوب لوز لنقطة         ║
║     الدخول**… في حال ما انعكس كفّه للتي بي الثاني **بقرّب الستوب   ║
║     لوز للهدف الأوّل**. في حال أخذنا التي بي 3 **بقرّب ستوب لوز    ║
║     للهدف الثاني**»                                              ║
║                                                                  ║
║  ⇒ فالدرجات 2 فصاعدًا **`SOURCE`**، والمستخدم كان ناقلًا لا        ║
║  مخترعًا — **للمرّة الثانية** (انظر التصحيح أدناه).                ║
║  ⚠️ **ولم يتغيّر سلوكٌ**: الكود كان مطابقًا. تغيّر مَن يُنسب إليه. ║
╚══════════════════════════════════════════════════════════════════╝

╔══════════════════════════════════════════════════════════════════╗
║  ⛔⛔ **تصحيح (2026-09-20، بعد البناء):**                         ║
║                                                                  ║
║  قلتُ للمستخدم إنّ قاعدته «ينقل الوقف إلى **الدخول**» **تخالف**   ║
║  المدرّب. **وكان ذلك خطأً** — فللمدرّب نصٌّ ثانٍ يقول ما قاله      ║
║  المستخدم حرفيًّا، في درسٍ آخر (≈13:13):                          ║
║                                                                  ║
║    «لمّا بدك تأمّن الصفقة **بدك تأمّنها على نقطة الدخول**. ما بدك  ║
║     تأمّنها **فوق فوق** — يعني انت عم تأمّن **مربحيتك**، انت مش    ║
║     عم تأمّن **الصفقة**»                                          ║
║                                                                  ║
║  فلم يكن المستخدم مخالفًا؛ كان ناقلًا عن نصٍّ لم أكن فهرستُه.      ║
╚══════════════════════════════════════════════════════════════════╝

**والنصّان يتّسقان، ولا يُرجَّح أحدهما بالرأي:** الثاني ينهى عن
التأمين **«فوق فوق»** — مكرَّرةً، أي بعيدًا فوق الدخول — وعلّتُه أنّ
ذلك تأمينُ ربحٍ لا تأمينُ صفقة. والأوّل يعطي المقدار: **دولارٌ
واحد**، وعلّتُه **الخروج صفرًا** لا الخروج رابحًا. فالدولار ليس
«فوق فوق»: هو أقلُّ ما يجعل الصفر صفرًا.

⇒ فالمبنيُّ هنا يُرضي النصّين معًا. 🔶 ولو ظهر نصٌّ ثالث يحسمها
لغير ذلك، فالمفتاح `plus=0.0` يعطي الدخول الحرفيّ بسطر.

⛔ **ولا يُضاف الدولار إلى الدرجات التالية**: علّتُه تغطيةُ السبريد
عند التعادل، وعند الهدف الأوّل صار الربحُ المحجوز يغطّيه.

╔══════════════════════════════════════════════════════════════════╗
║  🔶 **والسطرُ أعلاه معارَضٌ بنصّ — 2026-09-26.** ففي درس الأهداف   ║
║  والوقف يضع المدرّب هامشًا عند **كلّ** درجة، لا الأولى وحدها:      ║
║                                                                  ║
║    «نزّلت الستوب لوز لنقطة الدخول **أدناها بقليل** — مشان إذا في  ║
║     حال كسر السعر **بفرق السبريد** ما يوقعك بخساير» (17:26)       ║
║    «جاب الهدف الثاني نزّلت الستوب لوز **لعند الهدف الأوّل وكمان…   ║
║     بقليل** — مشان **ما يسحبوا على السب[ريد]**» (17:47)           ║
║                                                                  ║
║  **وعلّتُه مختلفةٌ عن علّتنا**: ليست تغطيةَ خسارةٍ عند التعادل،    ║
║  بل **منعَ السحب على السبريد** — وهي لا يبطلها الربحُ المحجوز،     ║
║  لأنّ وقفًا عند الهدف الأوّل بالضبط يُسحب بفرق السبريد تمامًا كما  ║
║  يُسحب وقفٌ عند الدخول بالضبط.                                    ║
║                                                                  ║
║  ⛔ **ولم يُطبَّق — قِس قبل أن تغيّر.** والتفريغُ مضطربٌ في الكلمة ║
║  التي تحدّد الاتّجاه («وكمان اعلابي قليل»)، والأثرُ يمسّ الصفقاتِ  ║
║  التي **تبلغ الهدف الثاني** ولم يُحصَ كم منها في الاثنتي عشرة.     ║
║  ⇒ البندُ مسجَّلٌ في `params.py::TRAIL_SPREAD_MARGIN_EVERY_RUNG`.  ║
╚══════════════════════════════════════════════════════════════════╝
"""

from __future__ import annotations

from dataclasses import dataclass
from typing import Literal, Optional, Sequence

Direction = Literal["buy", "sell"]

# «بترفع الستوب لوز لفوق دخولك **بدولار**» — الأوردر بلوك ج3
BREAK_EVEN_PLUS = 1.00


def stop_after(
    entry: float,
    initial_stop: float,
    targets: Sequence[float],
    reached: int,
    direction: Direction,
    plus: float = BREAK_EVEN_PLUS,
) -> float:
    """
    أين يقف الوقفُ بعد بلوغ `reached` هدفًا؟

    `reached = 0` ⇒ الوقف الأصليّ — فلا تأمين قبل الهدف الأوّل:
    «**بس ضرب الهدف الأوّل**، بدك تأمّن».
    """
    if reached <= 0:
        return initial_stop
    if reached == 1:
        return entry + plus if direction == "buy" else entry - plus
    # بعد الهدف k ⇒ الوقف عند الهدف k−1
    i = min(reached, len(targets)) - 2
    return targets[i] if 0 <= i < len(targets) else initial_stop


def never_looser(direction: Direction, old: float, new: float) -> float:
    """
    ⛔ **والوقف لا يتراجع أبدًا.**

    والسلّمُ لا يتراجع بذاته ما دامت الأهداف مرتّبة — لكنّ هدفًا
    أقربَ من الدخول (وذلك ممكنٌ في سيولةٍ مزدحمة) يُرخي الوقفَ بدل
    أن يشدّه. فيُمنع هنا، لا في نيّة المستعمل.
    """
    return max(old, new) if direction == "buy" else min(old, new)


@dataclass(frozen=True)
class Step:
    """نقلةُ وقفٍ واحدة — للعرض في السجلّ."""

    after_target: int         # بعد أيّ هدف
    stop: float
    why: str

    def render(self) -> str:
        return f"بعد الهدف {self.after_target} ⇒ الوقف {self.stop:.2f} ({self.why})"


def ladder(
    entry: float,
    initial_stop: float,
    targets: Sequence[float],
    direction: Direction,
    plus: float = BREAK_EVEN_PLUS,
) -> list[Step]:
    """
    سلّمُ النقلات كاملًا — يُعرَض مع الإعداد قبل أن يُفتح.

    ⭐ فالمستخدم يرى **متى سيتحرّك وقفُه** قبل الدخول لا بعده.
    """
    out: list[Step] = []
    stop = initial_stop
    for k in range(1, len(targets) + 1):
        raw = stop_after(entry, initial_stop, targets, k, direction, plus)
        stop = never_looser(direction, stop, raw)
        why = (f"الدخول {entry:.2f} + {plus:g}$" if k == 1
               else f"الهدف {k - 1}")
        out.append(Step(k, stop, why))
    return out
